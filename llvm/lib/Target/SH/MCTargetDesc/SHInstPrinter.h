#ifndef LLVM_LIB_TARGET_SH_MCTARGETDESC_SHINSTPRINTER_H
#define LLVM_LIB_TARGET_SH_MCTARGETDESC_SHINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class SHInstPrinter : public MCInstPrinter {
public:
  SHInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &OS) override;
  void printRegName(raw_ostream &OS, MCRegister Reg) override;
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printBranchTarget(const MCInst *MI, uint64_t Address, unsigned OpNo,
                         raw_ostream &OS);
  void printSImm8(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printLongMemReg(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printLongMemDisp(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printNarrowMemDisp(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printPreDecGPR(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printPostIncGPR(const MCInst *MI, unsigned OpNo, raw_ostream &OS);

  // Autogenerated by TableGen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &OS);
  bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &OS);
  static const char *getRegisterName(MCRegister Reg);
};

} // namespace llvm

#endif
